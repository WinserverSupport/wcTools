#!/usr/bin/env python
# wcat-spool-args.py -- build wcrun nvpair arguments from spool .D/.X pairs
#
# The wcUUCP-era spool pair (predating wcSMTP) holds what an smtpfilter
# hook is invoked with:
#
#   <name>.D   the message.  FIRST LINE is the Return-Path, i.e. the
#              5321.MAIL FROM.  By long-standing practice that line is
#              stripped before the message is stored, so it is present
#              here but not in the final conference copy.
#   <name>.X   the delivery instructions.  The "C rmail <addr>" line
#              carries the 5321.RCPT TO.
#
# Emits the quoted argument string for:
#
#   wcrun -r smtpfilter-cleanspam.wcx "psf=...&rcpt=...&from=..."
#
# Usage:
#   python wcat-spool-args.py <dir-or-file> [options]
#
# Options:
#   --wcx <name>      emit full wcrun command lines for this .wcx
#   --psf-dir <dir>   override the psf= path (default: the .D location)
#   --cmd             emit a .cmd batch of every wcrun line
#
# Examples:
#   python wcat-spool-args.py c:\wc10beta32\spool\Defaulthost\done
#   python wcat-spool-args.py c:\wc10beta32\spool\Defaulthost\done\064140W.D
#   python wcat-spool-args.py <dir> --wcx smtpfilter-cleanspam.wcx --cmd > run.cmd
#
# Revision History:
# 500.2  08/28/26  Initial version

import os
import sys
import glob
import argparse

try:
    sys.stdout.reconfigure(encoding='cp437', errors='replace')
    sys.stderr.reconfigure(encoding='cp437', errors='replace')
except (AttributeError, ValueError):
    pass


def read_lines(path, limit=None):
    """Read a spool file as CP437 (raw 8-bit, as the BBS stored it)."""
    out = []
    with open(path, 'rb') as f:
        for n, raw in enumerate(f):
            out.append(raw.decode('cp437', errors='replace').rstrip('\r\n'))
            if limit and n + 1 >= limit:
                break
    return out


def strip_brackets(s):
    s = s.strip()
    if s.startswith('<') and s.endswith('>'):
        s = s[1:-1]
    return s.strip()


def get_mailfrom(dfile):
    """5321.MAIL FROM -- first line of the .D, the Return-Path."""
    lines = read_lines(dfile, limit=1)
    if not lines:
        return ''
    first = lines[0]
    # Accept both a bare address and a "Return-Path: <addr>" form.
    if first.lower().startswith('return-path:'):
        first = first.split(':', 1)[1]
    return strip_brackets(first)


def get_rcpt(xfile):
    """5321.RCPT TO -- the 'C rmail <addr>' line of the .X."""
    for line in read_lines(xfile):
        s = line.strip()
        if not s:
            continue
        # "C rmail hsantos@isdg.net"  (tolerate extra args/quoting)
        if s[:1].upper() == 'C' and 'rmail' in s.lower():
            parts = s.split()
            for p in parts[1:]:
                if p.lower() == 'rmail':
                    continue
                if '@' in p:
                    return strip_brackets(p)
    return ''


def find_x(dfile):
    """Locate the .X partner; the extension case varies (.x seen on NTBBS)."""
    base = os.path.splitext(dfile)[0]
    for ext in ('.X', '.x'):
        p = base + ext
        if os.path.exists(p):
            return p
    return None


def collect(target):
    if os.path.isdir(target):
        files = sorted(glob.glob(os.path.join(target, '*.D')) +
                       glob.glob(os.path.join(target, '*.d')))
    else:
        files = [target]
    # de-dup: a case-insensitive filesystem can return both spellings
    seen = set()
    out = []
    for f in files:
        k = os.path.normcase(os.path.abspath(f))
        if k not in seen:
            seen.add(k)
            out.append(f)
    return out


def main():
    parser = argparse.ArgumentParser(
        description="Build wcrun nvpair arguments from spool .D/.X pairs")
    parser.add_argument('target', help="spool directory or a single .D file")
    parser.add_argument('--wcx', default='', help="emit full wcrun command lines")
    parser.add_argument('--psf-dir', default='', help="override the psf= directory")
    parser.add_argument('--cmd', action='store_true', help="emit a .cmd batch")
    args = parser.parse_args()

    dfiles = collect(args.target)
    if not dfiles:
        print("No .D files found in {}".format(args.target))
        sys.exit(1)

    if args.cmd:
        print("@echo off")
        print("REM generated by wcat-spool-args.py")
        print("")

    ok = 0
    for dfile in dfiles:
        xfile = find_x(dfile)
        if not xfile:
            print("REM SKIP {} - no matching .X".format(dfile))
            continue

        mailfrom = get_mailfrom(dfile)
        rcpt = get_rcpt(xfile)
        if not rcpt:
            print("REM SKIP {} - no 'C rmail' line in {}".format(
                dfile, os.path.basename(xfile)))
            continue

        psf = dfile
        if args.psf_dir:
            psf = os.path.join(args.psf_dir, os.path.basename(dfile))

        nv = 'psf={}&rcpt={}&from={}'.format(psf, rcpt, mailfrom)
        if args.wcx:
            print('wcrun -r {} "{}"'.format(args.wcx, nv))
        else:
            print('"{}"'.format(nv))
        ok += 1

    if not args.cmd:
        print("")
        print("Pairs: {} of {}".format(ok, len(dfiles)))


if __name__ == "__main__":
    main()
